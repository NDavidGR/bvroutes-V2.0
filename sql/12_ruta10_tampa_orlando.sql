-- Solo crea las que no existan ya (por nombre normalizado) y las pone en la ruta 10 sin posición.
with ins as (
  insert into public.stops(name, name_key, lat, lng, coord_source, note, type)
  select s.name, s.name_key, s.lat, s.lng, 'kml', s.note, 'customer'
  from tmp_r10 s
  where not exists (select 1 from public.stops x where x.name_key = s.name_key)
  returning id
)
insert into public.route_stops(route_id, stop_id, position)
select '10', id, null from ins;

-- Resultado: cuántas quedaron en la ruta 10 y cuáles se saltó porque ya existía una parada con ese nombre.
select 'en ruta 10' as concepto, count(*)::text as detalle from public.route_stops where route_id = '10'
union all
select 'saltada (ya existía)', s.name from tmp_r10 s
  where exists (select 1 from public.stops x where x.name_key = s.name_key)
    and not exists (select 1 from public.route_stops r join public.stops x on x.id = r.stop_id where r.route_id = '10' and x.name_key = s.name_key);
